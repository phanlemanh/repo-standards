#!/usr/bin/env python3
"""Autonomy gate: classify a change as low / medium / high using governance/autonomy.yaml.

  python3 tools/autonomy.py --base origin/main --head HEAD        # tier of a branch/PR
  python3 tools/autonomy.py --files a.py docs/x.md                 # tier of given paths
  python3 tools/autonomy.py --base ... --github                    # write GitHub outputs/summary
  python3 tools/autonomy.py --write-codeowners                     # render .github/CODEOWNERS
  python3 tools/autonomy.py --check-codeowners                     # fail if CODEOWNERS is stale

Options for dependency bots: --author dependabot[bot] --update-type version-update:semver-patch

In CI, run the copy of this script from the BASE branch, so a pull request cannot
change the rules that judge it (changes to tools/ and governance/ are "high" anyway).
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))
from repo_ontology import find_repo_root, load_yaml_file

TIERS = ["low", "medium", "high"]
CODEOWNERS_BEGIN = "# BEGIN generated by tools/autonomy.py from governance/autonomy.yaml"
CODEOWNERS_END = "# END generated"
LOCKFILES = {"package-lock.json", "pnpm-lock.yaml", "yarn.lock", "uv.lock", "poetry.lock"}
MANIFESTS = {"package.json", "pyproject.toml", "requirements.txt"}
TEST_PATH = re.compile(r"(^|/)tests?/|\.test\.|\.spec\.|(^|/)test_")
# Added lines that switch tests off without deleting anything.
TEST_DISABLED = re.compile(
    r"\.(?:skip|skipIf|only|runIf|todo)\b|\bx(?:it|describe|test)\b"
    r"|\bpytest\.(?:mark\.)?(?:skip|xfail)|\bunittest\.skip|\bcollect_ignore"
)


def glob_to_regex(pattern: str) -> re.Pattern[str]:
    i, out = 0, []
    while i < len(pattern):
        if pattern.startswith("**/", i):
            out.append("(?:.*/)?")
            i += 3
        elif pattern.startswith("**", i):
            out.append(".*")
            i += 2
        elif pattern[i] == "*":
            out.append("[^/]*")
            i += 1
        elif pattern[i] == "?":
            out.append("[^/]")
            i += 1
        else:
            out.append(re.escape(pattern[i]))
            i += 1
    return re.compile("^" + "".join(out) + "$")


def load_policy(root: Path, path: str | None = None) -> dict[str, Any]:
    policy = load_yaml_file(Path(path) if path else root / "governance" / "autonomy.yaml")
    if not isinstance(policy, dict):
        raise SystemExit("governance/autonomy.yaml is missing or not a mapping")
    return policy


def matches(path: str, patterns: list[str]) -> bool:
    return any(glob_to_regex(str(p)).match(path) for p in patterns)


def changed_files(root: Path, base: str, head: str) -> list[dict[str, Any]]:
    def git(*args: str) -> str:
        return subprocess.run(  # noqa: S603
            ["git", *args],  # noqa: S607
            cwd=root,
            capture_output=True,
            encoding="utf-8",
            errors="replace",
            check=True,
        ).stdout

    # --no-renames: a rename counts as delete + add, so the old path is judged too.
    # -z: paths arrive unquoted, so patterns also match non-ASCII names.
    span = f"{base}...{head}"
    stats: dict[str, tuple[int, int]] = {}
    for record in git("diff", "--no-renames", "-z", "--numstat", span).split("\0"):
        if record:
            added, deleted, path = record.split("\t", 2)
            stats[path] = (
                int(added) if added.isdigit() else 0,
                int(deleted) if deleted.isdigit() else 0,
            )
    tokens = git("diff", "--no-renames", "-z", "--name-status", span).split("\0")
    files: list[dict[str, Any]] = []
    # strict=False: the output ends with a NUL, so the split leaves one extra empty token.
    for status, path in zip(tokens[0::2], tokens[1::2], strict=False):
        n_added, n_deleted = stats.get(path, (0, 0))
        entry = {"path": path, "status": status[0], "added": n_added, "deleted": n_deleted}
        if TEST_PATH.search(path) and status[0] != "D":
            patch = git("--literal-pathspecs", "diff", "--no-renames", "-U0", span, "--", path)
            entry["disables_tests"] = any(
                line.startswith("+") and not line.startswith("+++") and TEST_DISABLED.search(line)
                for line in patch.splitlines()
            )
        files.append(entry)
    return files


def classify(
    policy: dict[str, Any],
    files: list[dict[str, Any]],
    author: str = "",
    update_type: str = "",
) -> dict[str, Any]:
    default = str(policy.get("default", "medium"))
    rules = policy.get("rules") or {}
    results = []
    for f in files:
        path = f["path"]
        if matches(path, policy.get("high") or []):
            tier, reason = "high", "protected path"
        elif matches(path, policy.get("low") or []):
            tier, reason = "low", "low-risk path"
            weakened = f.get("deleted", 0) > 0 or f.get("status") == "D" or f.get("disables_tests")
            if TEST_PATH.search(path) and weakened:
                tier = str(rules.get("test_deletions_raise_to", "medium"))
                reason = "removes, rewrites or disables test code"
        else:
            tier, reason = default, "default"
        results.append({**f, "tier": tier, "reason": reason})

    # Dependency bot: only manifests/lockfiles changed -> tier by semver level.
    dep_rules = rules.get("dependency_updates") or {}
    if (
        author.startswith(("dependabot", "renovate"))
        and results
        and all(Path(r["path"]).name in LOCKFILES | MANIFESTS for r in results)
    ):
        level = update_type.rsplit("-", 1)[-1] if update_type else "major"
        tier = str(dep_rules.get(level, "high"))
        for r in results:
            r["tier"], r["reason"] = tier, f"dependency update ({level})"

    overall = max((r["tier"] for r in results), key=TIERS.index, default="low")
    return {"tier": overall, "files": results}


def render_codeowners(policy: dict[str, Any]) -> str:
    owners = policy.get("owners") or {}
    medium = " ".join(owners.get("medium") or [])
    high = " ".join(owners.get("high") or [])
    lines = [
        CODEOWNERS_BEGIN,
        "# Do not edit this block by hand: change governance/autonomy.yaml, run `make codeowners`.",
        "# Last matching pattern wins. Low-tier paths have no owner: agents may merge them.",
        f"*  {medium}".rstrip(),
        "",
        "# low",
    ]
    lines += [
        f"/{p.lstrip('/')}" if "/" in p and not p.startswith("**") else p
        for p in policy.get("low") or []
    ]
    lines += ["", "# high"]
    lines += [
        (f"/{p.lstrip('/')}" if "/" in p and not p.startswith("**") else p) + f"  {high}"
        for p in policy.get("high") or []
    ]
    lines.append(CODEOWNERS_END)
    return "\n".join(lines) + "\n"


def codeowners_block(text: str) -> str:
    if CODEOWNERS_BEGIN not in text:
        return ""
    start = text.index(CODEOWNERS_BEGIN)
    end = text.index(CODEOWNERS_END, start) + len(CODEOWNERS_END)
    return text[start:end] + "\n"


def write_github(result: dict[str, Any]) -> None:
    out = os.environ.get("GITHUB_OUTPUT")
    if out:
        with open(out, "a", encoding="utf-8") as fh:
            fh.write(f"tier={result['tier']}\n")
    summary = os.environ.get("GITHUB_STEP_SUMMARY")
    if summary:
        rows = "\n".join(
            f"| `{r['path']}` | {r['tier']} | {r['reason']} |"
            for r in sorted(result["files"], key=lambda r: -TIERS.index(r["tier"]))
        )
        with open(summary, "a", encoding="utf-8") as fh:
            fh.write(
                f"## Autonomy tier: **{result['tier']}**\n\n"
                "| File | Tier | Why |\n| --- | --- | --- |\n" + rows + "\n"
            )


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--root", default=None)
    ap.add_argument("--policy", default=None, help="policy file (default governance/autonomy.yaml)")
    ap.add_argument("--base")
    ap.add_argument("--head", default="HEAD")
    ap.add_argument("--files", nargs="*")
    ap.add_argument("--author", default="")
    ap.add_argument("--update-type", default="")
    ap.add_argument("--github", action="store_true", help="write GITHUB_OUTPUT and step summary")
    ap.add_argument("--write-codeowners", action="store_true")
    ap.add_argument("--check-codeowners", action="store_true")
    args = ap.parse_args(argv)

    root = Path(args.root).resolve() if args.root else find_repo_root()
    policy = load_policy(root, args.policy)
    codeowners = root / ".github" / "CODEOWNERS"

    if args.write_codeowners or args.check_codeowners:
        block = render_codeowners(policy)
        current = codeowners.read_text(encoding="utf-8") if codeowners.exists() else ""
        if args.check_codeowners:
            if codeowners_block(current) != block:
                print(
                    ".github/CODEOWNERS is out of date with governance/autonomy.yaml. "
                    "Run: make codeowners",
                    file=sys.stderr,
                )
                return 1
            print("CODEOWNERS matches governance/autonomy.yaml")
            return 0
        old = codeowners_block(current)
        text = current.replace(old, block) if old else (current + ("\n" if current else "") + block)
        codeowners.parent.mkdir(parents=True, exist_ok=True)
        codeowners.write_text(text, encoding="utf-8")
        print("wrote .github/CODEOWNERS")
        return 0

    if args.files is not None:
        files = [{"path": p, "status": "M", "added": 0, "deleted": 0} for p in args.files]
    elif args.base:
        files = changed_files(root, args.base, args.head)
    else:
        ap.error("give --base (and --head) or --files")
    result = classify(policy, files, args.author, args.update_type)
    if args.github:
        write_github(result)
    print(json.dumps(result, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
